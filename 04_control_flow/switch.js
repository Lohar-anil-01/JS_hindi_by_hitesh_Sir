/* Example of switch statement */
const month = "Apr";

switch (month) {
    case "Jan":
        console.log("Its January");
        break;

    case "Feb":
        console.log("Its February");
        break;

    case "Mar":
        console.log("Its March");
        break;

    case "Apr":
        console.log("Its April");
        break;

    default:
        console.log("Default case match");
        break;
}